import { z } from "zod"
import { calendarDate, CalendarDateError, type CalendarDate } from "../../domain/calendar-date"
import { positiveRupees } from "./rupees"

// What a client may send to record, edit, delete or restore a transaction. Strict like the node schemas: `userId`,
// `groupId`, `version` and the like are errors, not silently dropped, so the form a user filled in and the row that is
// written agree. Rupee text becomes paise and day text becomes a CalendarDate here, as validation issues, so the
// service only ever sees real values. No server imports, so a client form can reuse it; relative imports as in node.ts.

export const NOTE_MAX_LENGTH = 500
export const TAG_MAX_LENGTH = 40
export const TAGS_MAX = 20
// An idempotency key identifies one submission of a form, generated by the client (a UUID is 36 characters). An empty
// key is refused outright: the repository treats "" as no key while the insert stores it, so a repeated "" would
// surface as a raw database error instead of a replay. The minimum also keeps keys unguessable and unlikely to collide.
export const IDEMPOTENCY_KEY_MIN_LENGTH = 16
export const IDEMPOTENCY_KEY_MAX_LENGTH = 128

const nodeId = z.string().min(1)
const transactionId = z.string().min(1)

const occurredAt = z.string().transform((text, ctx): CalendarDate => {
  try {
    return calendarDate(text)
  } catch (error) {
    if (!(error instanceof CalendarDateError)) throw error
    ctx.addIssue({ code: "custom", message: "Enter a valid date" })
    return z.NEVER
  }
})
const note = z.string().trim().max(NOTE_MAX_LENGTH, `At most ${NOTE_MAX_LENGTH} characters`)
const tags = z.array(z.string().trim().min(1, "A tag cannot be empty").max(TAG_MAX_LENGTH)).max(TAGS_MAX)
const idempotencyKey = z
  .string()
  .min(IDEMPOTENCY_KEY_MIN_LENGTH, "A request key is required")
  .max(IDEMPOTENCY_KEY_MAX_LENGTH)

export const recordTransactionSchema = z.strictObject({
  fromNodeId: nodeId,
  toNodeId: nodeId,
  amount: positiveRupees,
  occurredAt,
  note: note.optional(),
  tags: tags.optional(),
  idempotencyKey,
})

// An edit names only what changes. `note: null` clears the note. The idempotency key is not editable: it belongs to the
// create.
const changes = z
  .strictObject({
    fromNodeId: nodeId,
    toNodeId: nodeId,
    amount: positiveRupees,
    occurredAt,
    note: note.nullable(),
    tags,
  })
  .partial()
  .refine((value) => Object.values(value).some((field) => field !== undefined), "Change at least one field")

export const editTransactionSchema = z.strictObject({
  id: transactionId,
  // The version the user was looking at: what makes a stale edit a conflict instead of a silent overwrite (EC-18).
  expectedVersion: z.number().int().min(0),
  changes,
})

export const transactionIdSchema = z.strictObject({ id: transactionId })
